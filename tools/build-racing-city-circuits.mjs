/** Offline route authoring. Every segment is an edge in Tirana Streets' WORLD.
 * Never run graph searches while loading the browser or authoritative server. */
import {writeFileSync} from 'node:fs';
import {WORLD} from '../webapp/src/games/tiranastreets/shared/world.mjs';
import {TIRANA_ROUTES} from '../webapp/src/games/kartroyale/tirana-routes.mjs';
import {roadGraph,routeLength} from '../webapp/src/games/kartroyale/grandRouteCore.mjs';
const key=p=>p.join(',');
function push(h,v){h.push(v);let i=h.length-1;while(i){const p=(i-1)>>1;if(h[p][0]<=v[0])break;h[i]=h[p];i=p;}h[i]=v;}
function pop(h){const first=h[0],last=h.pop();if(h.length){let i=0;while(i*2+1<h.length){let j=i*2+1;if(j+1<h.length&&h[j+1][0]<h[j][0])j++;if(h[j][0]>=last[0])break;h[i]=h[j];i=j;}h[i]=last;}return first;}
function path(g,a,b,blocked){
 const h=[],cost=new Map([[a,0]]),prev=new Map();push(h,[0,a]);
 while(h.length){const [d,u]=pop(h);if(cost.get(u)!==d)continue;if(u===b){const out=[b];while(out.at(-1)!==a)out.push(prev.get(out.at(-1)));return out.reverse();}
  for(const [v,e] of g.edges.get(u)||[]){if(blocked.has(v)&&v!==b)continue;const next=d+e.cost;if(next<(cost.get(v)??Infinity)){cost.set(v,next);prev.set(v,u);push(h,[next,v]);}}
 }return null;
}
const output=[];
for(const old of TIRANA_ROUTES){
 const center=old.points.reduce((s,p)=>[s[0]+p[0]/old.points.length,s[1]+p[1]/old.points.length],[0,0]);
 const g=roadGraph(WORLD.roads.filter(r=>Math.hypot(r.a[0]-center[0],r.a[1]-center[1])<1900));
 const nodes=[...g.nodes].filter(([k])=>g.edges.get(k).size>=3);
 const nearest=p=>nodes.reduce((best,n)=>Math.hypot(n[1][0]-p[0],n[1][1]-p[1])<Math.hypot(best[1][0]-p[0],best[1][1]-p[1])?n:best)[0];
 let best;
 const starts=nodes.filter(([id])=>old.points.some(p=>key(p)===id)).map(n=>n[0]);
 for(const start of [nearest(center),...starts]) {
 for(const radius of [450,650,950,1250,1500])for(let i=0;i<16;i++){
  const angle=i*Math.PI/8;
  const a=nearest([center[0]+Math.cos(angle)*radius,center[1]+Math.sin(angle)*radius]);
  const b=nearest([center[0]+Math.cos(angle+2.2)*radius,center[1]+Math.sin(angle+2.2)*radius]);
  if(new Set([start,a,b]).size!==3)continue;
  const first=path(g,start,a,new Set([b]));if(!first)continue;
  const second=path(g,a,b,new Set(first.slice(0,-1)));if(!second)continue;
  const third=path(g,b,start,new Set([...first.slice(1),...second.slice(0,-1)]));if(!third)continue;
  const ids=[...first,...second.slice(1),...third.slice(1,-1)];if(new Set(ids).size!==ids.length)continue;
  const points=ids.map(id=>g.nodes.get(id));const length=routeLength(points);
  if(length<Math.max(3200,routeLength(old.points)*2.6)||length>6500)continue;
  const edges=ids.map((id,j)=>g.edges.get(id).get(ids[(j+1)%ids.length]));
  const candidate={id:old.id,points,widths:edges.map(e=>Math.min(12,e.width)),streets:[...new Set(edges.map(e=>e.name).filter(Boolean))].sort(),length,originalLength:routeLength(old.points)};
  if(!best||Math.abs(length-5200)<Math.abs(best.length-5200))best=candidate;
 }
 }
 if(!best)throw Error('No validated long route for '+old.id);

 console.log(old.id,Math.round(best.length),best.points.length,'nodes');output.push(best);
}
const meta={source:WORLD.source,attribution:WORLD.attribution,version:'tirana-city-2026-09',description:'Closed race courses on the same checked-in street network as Tirana Streets; not legal road itineraries.',routes:output};
writeFileSync(new URL('../webapp/src/games/kartroyale/city-circuits.mjs',import.meta.url),'// Generated by tools/build-racing-city-circuits.mjs. © OpenStreetMap contributors, ODbL.\nexport const CITY_CIRCUITS = '+JSON.stringify(meta)+';\n');
