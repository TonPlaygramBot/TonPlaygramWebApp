// Keep Racing's shipped rural circuits independent of the city game's crop.
// Source coordinates/widths/footprints are copied, never inferred from proximity.
import {writeFile} from 'node:fs/promises';
import {gzipSync} from 'node:zlib';
import assert from 'node:assert/strict';
import {WORLD} from '../webapp/src/games/tiranastreets/shared/world.mjs';
import {NEIGHBOURHOOD} from '../webapp/src/games/tirana-neighbourhood/sourceData.mjs';
import {EAST} from '../webapp/src/games/tirana-east/sourceData.mjs';
import {RURAL_ROUTES} from '../webapp/src/games/kartroyale/rural-routes.mjs';

const key=r=>[r.a.join(','),r.b.join(',')].sort().join('|');
const cityRoads=new Set(WORLD.roads.map(key)),cityBuildings=new Set(WORLD.buildings.map(b=>String(b.id)));
const routes=RURAL_ROUTES.filter(r=>r.points.some((a,i)=>!cityRoads.has(key({a,b:r.points[(i+1)%r.points.length]}))));
const bounds=p=>[Math.min(...p.map(v=>v[0])),Math.min(...p.map(v=>v[1])),Math.max(...p.map(v=>v[0])),Math.max(...p.map(v=>v[1]))];
const regions=routes.map(r=>({id:r.id,bounds:bounds(r.points).map((n,i)=>n+(i<2?-240:240))}));
const nearby=points=>{const b=bounds(points);return regions.some(r=>b[0]<=r.bounds[2]&&b[2]>=r.bounds[0]&&b[1]<=r.bounds[3]&&b[3]>=r.bounds[1]);};
const roads=new Map(),buildings=new Map(),waterAreas=new Map();
for(const source of [NEIGHBOURHOOD,EAST]){
 for(const r of source.roads)if(!cityRoads.has(key(r))&&nearby([r.a,r.b])&&!roads.has(key(r)))roads.set(key(r),r);
 for(const b of source.buildings)if(!cityBuildings.has(String(b.id))&&nearby(b.p)&&!buildings.has(String(b.id)))buildings.set(String(b.id),b);
 for(const w of source.water||[])if(w.polygons?.some(p=>nearby(p.outer)))waterAreas.set(w.id,w);
}
for(const r of routes)for(let i=0;i<r.points.length;i++){
 const edge=key({a:r.points[i],b:r.points[(i+1)%r.points.length]});
 assert.ok(cityRoads.has(edge)||roads.has(edge),`${r.id}: archived road missing at ${i}`);
}
const data={regions,roads:[...roads.values()],buildings:[...buildings.values()],waterAreas:[...waterAreas.values()],attribution:'© OpenStreetMap contributors, ODbL 1.0'};
const packed=gzipSync(JSON.stringify(data),{level:9}).toString('base64').match(/.{1,64000}/g);
const output="// © OpenStreetMap contributors, ODbL 1.0. Generated by tools/build-racing-rural-world.mjs.\nimport {decodeSource} from '../tirana-neighbourhood/decodeSource.mjs';\nexport const RURAL_WORLD=decodeSource("+JSON.stringify(packed)+');\n';
await writeFile(new URL('../webapp/src/games/kartroyale/ruralWorldData.mjs',import.meta.url),output);
console.log(JSON.stringify({regions:regions.map(r=>r.id),roads:roads.size,buildings:buildings.size,waterAreas:waterAreas.size,bytes:output.length}));
