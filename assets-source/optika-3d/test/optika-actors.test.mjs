import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as T from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { clone } from 'three/examples/jsm/utils/SkeletonUtils.js';
const pathFor=(base)=>fileURLToPath(new URL('../../../webapp/public/assets/optika-3d-v1/worlds/'+base+'.glb',import.meta.url));
const load=async base=>{
 const bytes=await readFile(pathFor(base));
 assert.equal(bytes.toString('ascii',0,4),'glTF');
 assert.equal(bytes.readUInt32LE(4),2);
 assert.equal(bytes.length,bytes.readUInt32LE(8));
 const json=JSON.parse(bytes.toString('utf8',20,20+bytes.readUInt32LE(12)));
 assert.equal(json.images?.length??0,0,'must embed no photo, logo or third-party image');
 assert.equal(json.textures?.length??0,0);
 assert(!json.buffers.some(b=>b.uri));
 const gltf=await new GLTFLoader().parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
 return {json,gltf,bytes};
};
for(const name of ['hero','guard']) test(name+' loads as articulated cloned mesh; idle/walk/run loop, with physical standing height',async()=>{
 const {gltf}=await load(name);
 assert.deepEqual(gltf.animations.map(a=>a.name),['Idle','Walk','Run']);
 const a=clone(gltf.scene), b=clone(gltf.scene);
 assert.notEqual(a,b);
 // Same glTF API and normalization as the real Actor constructor.
 const box=new T.Box3().setFromObject(a,true);
 const h=box.max.y-box.min.y;
 assert(h>1.70&&h<1.88,h);
 assert(Math.abs(box.min.y)<.012);
 a.scale.multiplyScalar(1.8/h);
 a.position.y-=box.min.y*1.8/h;
 const box2=new T.Box3().setFromObject(a,true);
 assert(Math.abs(box2.min.y)<1e-5);
 assert(Math.abs(box2.max.y-1.8)<1e-5);
 const c=b.getObjectByName('Hip_L'), d=a.getObjectByName('Hip_L');
 assert(c&&d&&c!==d);
 const m=new T.AnimationMixer(a);
 const idle=m.clipAction(gltf.animations[0]); idle.play();
 m.update(.55);
 assert(Math.abs(a.getObjectByName('Head_Pivot').quaternion.y)>.004);
 idle.stop();
 const walk=m.clipAction(gltf.animations[1]); walk.play();
 m.update(.12);
 assert(Math.abs(d.quaternion.x)>.01);
 assert.equal(c.quaternion.x,0);
 walk.stop();
 const run=m.clipAction(gltf.animations[2]); run.play();
 m.update(.09);
 assert(Math.abs(d.quaternion.x)>.10);
 run.stop();
});
test('abstract first-person viewer loads without photographs and uses visible camera space',async()=>{
 const {gltf}=await load('rig-fpv');
 assert.equal(gltf.animations.length,0);
 const frame=gltf.scene.getObjectByName('Screen');
 assert(frame);
 gltf.scene.updateMatrixWorld(true);
 const camera=new T.PerspectiveCamera(60,390/844,.035,420);
 camera.updateMatrixWorld();
 const v=frame.getWorldPosition(new T.Vector3()).project(camera);
 assert(v.x>0&&v.x<1&&v.y<0&&v.y>-1&&v.z>-1&&v.z<1,JSON.stringify(v));
 assert(!gltf.scene.getObjectByName('Turi'));
});
