// Rebuild from Quaternius Universal Animation Library Standard v3 (CC0):
// node webapp/scripts/sample-tirana-humanoid-motions.mjs /path/to/UAL1_Standard.glb
// Only measured motion curves are shipped; each runtime rig keeps its own bones.
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import * as T from 'three';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
import {humanoidBones} from '../src/games/tiranastreets/street-career/humanoidRig.mjs';

if(!process.argv[2])throw Error('Pass the official Standard v3 in-place UAL1_Standard.glb');
const bytes=await readFile(process.argv[2]),loader=new GLTFLoader();
loader.register(()=>({name:'MOTION_ONLY_TEXTURES',loadTexture:async()=>new T.Texture()}));
const source=await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
source.scene.updateMatrixWorld(true);
const box=new T.Box3().setFromObject(source.scene),scale=1.76/(box.max.y-box.min.y),bones=humanoidBones(source.scene);
const names=['leftfoot','rightfoot','lefthand','righthand','hips'],v=new T.Vector3();
const point=name=>{bones.get(name).getWorldPosition(v);return [v.x*scale,(v.y-box.min.y)*scale,v.z*scale].map(n=>Math.round(n*10000)/10000);};
const rest=Object.fromEntries(names.map(name=>[name,point(name)]));
const clips={walk:'Walk_Loop',jog:'Jog_Fwd_Loop',sprint:'Sprint_Loop',idle:'Idle_Loop',cover:'Crouch_Idle_Loop',crouch:'Crouch_Fwd_Loop',hit:'Hit_Chest',headHit:'Hit_Head',jab:'Punch_Jab',cross:'Punch_Cross'};
const motions={},mixer=new T.AnimationMixer(source.scene),rate=30;
for(const [key,name] of Object.entries(clips)){
  const clip=source.animations.find(c=>c.name===name);if(!clip)throw Error(`Missing source clip ${name}`);
  mixer.stopAllAction();const action=mixer.clipAction(clip).reset().play(),count=Math.ceil(clip.duration*rate);
  const frames=[];
  for(let i=0;i<=count;i++){
    action.time=Math.min(clip.duration-1e-6,clip.duration*i/count);mixer.update(0);source.scene.updateMatrixWorld(true);
    frames.push(names.flatMap(point));
  }
  motions[key]={source:name,duration:Number(clip.duration.toFixed(6)),frames};
}
const result={source:'Quaternius Universal Animation Library Standard v3',license:'CC0-1.0',url:'https://quaternius.itch.io/universal-animation-library',sha256:createHash('sha256').update(bytes).digest('hex'),height:1.76,rate,names,rest,motions};
const out=new URL('../src/games/tiranastreets/street-career/data/humanoidMotions.mjs',import.meta.url);
await mkdir(new URL('.',out),{recursive:true});await writeFile(out,'// Generated by sample-tirana-humanoid-motions.mjs; CC0 motion curves.\nexport default '+JSON.stringify(result)+';\n');
console.log(`Sampled ${Object.keys(motions).length} authored motions into ${Buffer.byteLength(JSON.stringify(result))} bytes`);
