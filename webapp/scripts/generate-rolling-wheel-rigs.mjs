/** Preserve approved GLBs byte-for-byte. Regenerate triangle-to-axle partitions:
 * node webapp/scripts/generate-rolling-wheel-rigs.mjs
 * Uses the same pinned Three.js/Draco dependencies as the original asset tools. */
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {buildSync} from 'esbuild';
import {load} from './vehicle-wheels/loadAsset.mjs';
import {BIKE_TYPES} from '../src/games/tiranastreets/shared/bikeCatalog.mjs';
import {VEHICLE_COLLECTION} from '../src/games/tiranastreets/shared/vehicleCollection.mjs';
const temp=new URL('../node_modules/.cache/rolling-wheel-analyze.mjs',import.meta.url);
mkdirSync(new URL('.',temp),{recursive:true});
buildSync({entryPoints:[fileURLToPath(new URL('./vehicle-wheels/analyze.ts',import.meta.url))],outfile:fileURLToPath(temp),bundle:true,platform:'node',format:'esm',external:['three','three/*'],logLevel:'silent'});
const {analyzeWheelRig}=await import(temp);
const result={};
for(const asset of [...BIKE_TYPES,...VEHICLE_COLLECTION]){
 const path=new URL('../public'+asset.url,import.meta.url),root=await load(path);
 result[asset.id]={sha256:createHash('sha256').update(readFileSync(path)).digest('hex'),...analyzeWheelRig(root,BIKE_TYPES.includes(asset)?'bike':'collection')};
 console.log(asset.id,result[asset.id].wheels.length,'axles',Object.keys(result[asset.id].meshes).length,'partitioned meshes');
}
writeFileSync(new URL('../src/games/tiranastreets/shared/rollingWheelRigs.mjs',import.meta.url),'// Generated by webapp/scripts/generate-rolling-wheel-rigs.mjs. Original GLB bytes remain unchanged.\nexport default '+JSON.stringify(result)+';\n');
