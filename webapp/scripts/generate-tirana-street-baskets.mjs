import {writeFileSync} from 'node:fs';
import {WORLD} from '../src/games/tiranastreets-november/shared/world.mjs';
import {NEIGHBOURHOOD} from '../src/games/tirana-neighbourhood/data.mjs';
import {footprintIndex} from '../src/games/tirana-city-source/footprintIndex.mjs';
import {insidePolygon} from '../src/games/tiranastreets-november/shared/engine.mjs';
import {roadRing} from '../src/games/tirana-environment/roadSurfaceCore.mjs';
import {ALI_DEMI_FURNITURE} from '../src/games/tiranastreets-november/aliDemiFurniture.mjs';

// Reject doubtful placements, rather than moving mapped nodes into invented locations.
const roads = footprintIndex(WORLD.roads.filter(r=>!r.tunnel).map(r=>({...r,p:roadRing(r,r.w+5)})),64);
const solids = footprintIndex(WORLD.buildings,64,1);
const water = footprintIndex(NEIGHBOURHOOD.water.flatMap(w=>(w.polygons ?? []).map(p=>({p:p.outer,holes:p.holes}))),64,1);
const blocked = (edges, x, z) => edges.some(e=>insidePolygon(x,z,e.p)&&!e.holes?.some(h=>insidePolygon(x,z,h)));
const bins = [];
for (const place of NEIGHBOURHOOD.places) {
  if(place.tags.amenity !== 'waste_basket' || !place.point) continue;
  const [x,z] = place.point;
  if (ALI_DEMI_FURNITURE.some(p=>Math.hypot(p.x-x,p.z-z)<1.5) || bins.some(([,bx,bz])=>Math.hypot(x-bx,z-bz)<1)) continue;
  const nearby = roads(x,z);
  const traffic = nearby.filter(r=>!r.walk).flatMap(r=>{
    const p = roadRing(r,r.w+1.2,.64);
    return p ? [{p}] : [];
  });
  const paving = nearby.filter(r=>!r.bridge && !r.cycle).flatMap(r=>{
    const p = roadRing(r,r.w+(r.walk?0:3.8));
    return p ? [{p}] : [];
  });
  // Check full bin footprint, including clearance around facades, water or pavement ends.
  const sample = [0,-.45,.45].flatMap(dx=>[0,-.45,.45].map(dz=>[x+dx,z+dz]));
  if (!sample.every(([u,v])=>!blocked(traffic,u,v)&&!blocked(solids(u,v),u,v)&&!blocked(water(u,v),u,v))) continue;
  if (!sample.every(([u,v])=>blocked(paving,u,v))) continue;
  bins.push([place.id, x, z]);
}
const output = '// Generated by scripts/generate-tirana-street-baskets.mjs. Node locations: OpenStreetMap contributors (ODbL).\nexport const STREET_BASKETS = '+JSON.stringify(bins)+';\n';
writeFileSync(new URL('../src/games/tiranastreets-november/streetBasketsData.mjs',import.meta.url),output);
console.log(`${bins.length} mapped bins passed surface, clearance and duplicate checks.`);
