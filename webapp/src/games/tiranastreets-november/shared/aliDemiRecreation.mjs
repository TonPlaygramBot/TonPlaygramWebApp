/** Same metre projection as the Tirana world. Preserve adjacency at shared surveyed nodes. */
export function aliDemiSurfaces(origin) {
  const metresLon = 111320 * Math.cos(origin[0] * Math.PI / 180);
  const project = ([lat, lon]) => [(lon - origin[1]) * metresLon, (origin[0] - lat) * 111320];
  const feature = key => ALI_DEMI_SOURCE[key].ring.map(project);
  return {
    park: feature('park'), sportsCentre: feature('sportsCentre'), skate: feature('skate'),
    pitches: [feature('pitchNorth'), feature('pitchSouth')]
  };
}
export function aliDemiPlaces(origin) {
  const surfaces = aliDemiSurfaces(origin);
  return ['park', 'sportsCentre', 'skate'].map(key => {
    const ring = surfaces[key];
    const [x, z] = ring.reduce(([x, z], [a, b]) => [x + a / ring.length, z + b / ring.length], [0, 0]);
    const source = ALI_DEMI_SOURCE[key];
    return { id: `osm-way-${source.way}`, name: source.name, x, z };
  });
}
