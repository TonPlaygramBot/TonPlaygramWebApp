import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from '../webapp/node_modules/typescript/lib/typescript.js';
import * as T from '../webapp/node_modules/three/build/three.module.js';
import {makeTrack,createRacer} from '../webapp/src/games/kartroyale/simulation.mjs';
import {raceItemPickups} from '../webapp/src/games/kartroyale/raceItems.mjs';
let code=ts.transpileModule(readFileSync(new URL('../webapp/src/games/kartroyale/RaceItemEffects.ts',import.meta.url),'utf8'),{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
for(const [from,to] of [['three','../webapp/node_modules/three/build/three.module.js'],['./raceItems.mjs','../webapp/src/games/kartroyale/raceItems.mjs'],['./racingSurface.mjs','../webapp/src/games/kartroyale/racingSurface.mjs']])code=code.replace(`'${from}'`,JSON.stringify(new URL(to,import.meta.url).href));
const {RaceItemEffects}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
test('bounded item visuals match cooldown, shield and authoritative rocket heading',()=>{
 const track=makeTrack('skanderbeg'),me=createRacer(track,'you','You',0),effects=new RaceItemEffects();
 effects.update([me],me,track,2,true);
 const [boxes,rings,rockets,flames,shields]=effects.group.children;
 const count=raceItemPickups(track).length;
 assert.equal(boxes.count,count);assert.equal(rings.count,count);
 me.itemCooldowns={[raceItemPickups(track)[0].id]:10};me.itemShield=2;
 me.itemRocket={id:1,x:0,y:3,z:0,vx:52,vz:0,life:1};
 effects.update([me],me,track,3,true);
 assert.equal(boxes.count,count-1);assert.equal(shields.count,1);assert.equal(rockets.count,1);assert.equal(flames.count,1);
 const matrix=new T.Matrix4();rockets.getMatrixAt(0,matrix);
 const forward=new T.Vector3(0,1,0).transformDirection(matrix);
 assert.ok(forward.x>.999);assert.ok(Math.abs(forward.z)<1e-5);
 assert.equal(new T.Vector3().setFromMatrixPosition(matrix).y,3);
 const before=effects.group.children.length;
 for(let i=0;i<100;i++)effects.update([me],me,track,4+i/60,false);
 assert.equal(effects.group.children.length,before);
 effects.dispose();
});
